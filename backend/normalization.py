"""
وحدة تطبيع اللوحات المركزية (Central Plate Normalization Module)
=============================================================
قواعد التطبيع الصارمة لنظام مطابقة بيانات السيارات:
1. إزالة كافة أنواع المسافات:
   - المسافات العادية (Space)
   - المسافات غير القابلة للكسر (NBSP: \\u00A0, Narrow NBSP: \\u202F)
   - المسافات الصفرية (Zero-width spaces: \\u200B, \\u200C, \\u200D, \\uFEFF)
   - علامات الجدولة والأسطر الجديدة (\\t, \\r, \\n)
2. توحيد الأرقام المشرقية / الهندية والفارسية إلى الأرقام القياسية (0-9):
   - ٠١٢٣٤٥٦٧٨٩ -> 0123456789
   - ۰۱۲۳۴۵۶۷۸۹ -> 0123456789
3. إزالة الرموز والفواصل غير الضرورية:
   - الشرطات (- ، _)
   - الفواصل والنقاط (/ ، \\ ، . ، ، ، ,)
   - النجوم والرموز (* ، ~ ، : ، ;)
4. إزالة الكشيدة / التطويل العربي (ـ) وعلامات التشكيل والحركات.
5. توحيد حالة الأحرف الإنجليزية (تحويل إلى Lowercase) في حال وجدت.
6. الالتزام الصارم بقاعدة عدم التخمين:
   - عدم تبديل الحروف العربية ذات المعنى المختلف (مثل عدم تحويل ع إلى غ، أو د إلى ذ).
   - الاحتفاظ دائمًا بالقيمة الأصلية (Raw Plate) كما هي إلى جانب القيمة المطبعة (Normalized Plate).
"""

import re
import unicodedata

# جدول ترجمة الأرقام الشرقية والفارسية إلى أرقام قياسية
DIGIT_TRANSLATION = str.maketrans(
    '٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹',
    '01234567890123456789'
)

# نمط الرموز والمسافات والتشكيل والتطويل المستبعدة
# يشمل: المسافات بكافة أنواعها، الرموز، الفواصل، علامات التشكيل، التطويل
CLEANUP_PATTERN = re.compile(
    r'[\s\-_/\.\\,،\*~:;\"\'`|#+=\^?!@$%&()\[\]{}ـ\u00A0\u202F\u200B\u200C\u200D\uFEFF\u064B-\u065F\u0670]+'
)


def normalize_plate(raw_plate: any) -> str:
    """
    تطبيع لوحة السيارة وإعادتها بصيغة قياسية موحدة بدون مسافات أو رموز،
    مع تحويل الأرقام إلى الصيغة القياسية.

    أمثلة:
        " حكا 9053 "    ==> "حكا9053"
        "ح ك ا - ٩٠٥٣"  ==> "حكا9053"
        "ب د و / 1 2 3" ==> "بدو123"
        "A B C - 123"   ==> "abc123"

    المعاملات:
        raw_plate: القيمة الخام للوحة (نص أو رقم أو غيره)

    المخرجات:
        نص اللوحة بعد التطبيع الدقيق
    """
    if raw_plate is None:
        return ""

    # تحويل إلى نص
    text = str(raw_plate).strip()
    if not text:
        return ""

    # تسوية Unicode (NFKC) لتوحيد أشكال الحروف والرموز
    text = unicodedata.normalize('NFKC', text)

    # تحويل الأرقام المشرقية / الفارسية إلى قياسية
    text = text.translate(DIGIT_TRANSLATION)

    # إزالة الرموز والمسافات وعلامات التشكيل والتطويل
    text = CLEANUP_PATTERN.sub('', text)

    # توحيد الأحرف اللاتينية إلى lowercase إن وجدت
    text = text.lower()

    return text.strip()


def validate_plate_input(raw_plate: any) -> bool:
    """
    التحقق من أن المدخل يحتوي على قيمة صالحة بعد التطبيع.
    """
    norm = normalize_plate(raw_plate)
    return len(norm) > 0
